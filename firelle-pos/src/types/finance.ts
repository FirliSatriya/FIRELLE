/** Indonesian label for a category code, keeping auto codes readable. */
export function cashflowCategoryLabel(category: string): string {
  switch (category) {
    case "SALE":
      return "Penjualan POS";
    case "VOID":
      return "Pembatalan POS";
    case "Operational Expense":
      return "Biaya Operasional";
    case "Stock Purchase":
      return "Pembelian Stok";
    case "Rent":
      return "Sewa";
    case "Utilities":
      return "Utilitas";
    case "Salary":
      return "Gaji";
    case "Other Income":
      return "Pendapatan Lain";
    case "Other":
      return "Lainnya";
    default:
      return category;
  }
}

/** True when the row came from the system rather than a manual entry (BR-05). */
export function isAutoCashflow(row: { is_manual: boolean }): boolean {
  return !row.is_manual;
}

// ============================================================
// Date-range presets (WIB day boundaries — edge case §7.12)
// ============================================================

export type DateRangePreset =
  | "TODAY"
  | "THIS_WEEK"
  | "THIS_MONTH"
  | "CUSTOM";

export const DATE_RANGE_LABELS: Record<DateRangePreset, string> = {
  TODAY: "Hari Ini",
  THIS_WEEK: "Minggu Ini",
  THIS_MONTH: "Bulan Ini",
  CUSTOM: "Kustom",
};

export interface DateRange {
  /** Inclusive ISO start (UTC instant), or null when unbounded. */
  start: Date | null;
  /** Exclusive ISO end (UTC instant), or null when unbounded. */
  end: Date | null;
}

/**
 * Resolve a preset into concrete instants. WIB is a fixed UTC+7 offset (no
 * DST), so day boundaries are computed by shifting the instant then reading
 * the UTC calendar fields — this keeps "today" aligned with Jakarta midnight.
 *
 * `now` is passed in explicitly instead of being read here: with Cache
 * Components, reading the wall clock while a Client Component renders would
 * bake the prerender time into the static shell. Callers resolve "now" after
 * mount (or inside an effect/event handler) and pass it in.
 */
export function resolveDateRange(
  preset: DateRangePreset,
  custom: { start?: string; end?: string } | undefined,
  now: Date
): DateRange {
  if (preset === "CUSTOM") {
    return {
      start: custom?.start ? startOfDayWIB(custom.start) : null,
      end: custom?.end ? endOfDayWIBExclusive(custom.end) : null,
    };
  }

  if (preset === "TODAY") {
    const day = toWIBDateParts(now);
    return {
      start: wibDateToUtc(day.year, day.month, day.day, 0, 0, 0, 0),
      end: wibDateToUtc(day.year, day.month, day.day + 1, 0, 0, 0, 0),
    };
  }

  if (preset === "THIS_WEEK") {
    const day = toWIBDateParts(now);
    // Week starts Monday (Indonesian convention).
    const wibMidnight = wibDateToUtc(day.year, day.month, day.day, 0, 0, 0, 0);
    const weekday = (wibMidnight.getUTCDay() + 6) % 7; // 0 = Monday
    const start = wibDateToUtc(day.year, day.month, day.day - weekday, 0, 0, 0, 0);
    const end = wibDateToUtc(day.year, day.month, day.day - weekday + 7, 0, 0, 0, 0);
    return { start, end };
  }

  // THIS_MONTH
  const day = toWIBDateParts(now);
  return {
    start: wibDateToUtc(day.year, day.month, 1, 0, 0, 0, 0),
    end: wibDateToUtc(day.year, day.month + 1, 1, 0, 0, 0, 0),
  };
}

/** WIB calendar fields for an instant. */
function toWIBDateParts(date: Date): {
  year: number;
  month: number;
  day: number;
} {
  const shifted = new Date(date.getTime() + 7 * 60 * 60 * 1000);
  return {
    year: shifted.getUTCFullYear(),
    month: shifted.getUTCMonth() + 1,
    day: shifted.getUTCDate(),
  };
}

/** Build a UTC instant from WIB calendar fields (WIB = UTC+7). */
function wibDateToUtc(
  year: number,
  month: number,
  day: number,
  hour: number,
  minute: number,
  second: number,
  ms: number
): Date {
  const utc = Date.UTC(year, month - 1, day, hour, minute, second, ms);
  return new Date(utc - 7 * 60 * 60 * 1000);
}

/** WIB midnight at the start of an `YYYY-MM-DD` input value. */
export function startOfDayWIB(dateInput: string): Date {
  const [y, m, d] = dateInput.split("-").map(Number);
  return wibDateToUtc(y, m, d, 0, 0, 0, 0);
}

/** WIB midnight right after an `YYYY-MM-DD` input value (exclusive end). */
export function endOfDayWIBExclusive(dateInput: string): Date {
  const [y, m, d] = dateInput.split("-").map(Number);
  return wibDateToUtc(y, m, d + 1, 0, 0, 0, 0);
}

/** `YYYY-MM-DD` for a WIB day, for `<input type="date">` defaults. */
export function toWIBDateInput(date: Date): string {
  const shifted = new Date(date.getTime() + 7 * 60 * 60 * 1000);
  const y = shifted.getUTCFullYear();
  const m = String(shifted.getUTCMonth() + 1).padStart(2, "0");
  const d = String(shifted.getUTCDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
}